// One-entry-per-lang cache for the current process. Hooks run once per
// prompt/sweep invocation (short-lived processes), so this only saves
// repeat lookups within a single sweep run's multiple issue bodies.
const bundleCache = new Map<string, Record<string, string> | null>();

// Resolves and parses a locale bundle. Never throws — any failure (missing
// file, malformed JSON, non-object contents) is treated as "no overrides",
// which falls back to EN for every key. This mirrors the fail-open contract
// hooks/lib/work-config.ts already uses for repo-config breakage.
function loadLocaleBundle(lang: IssueLang): Record<string, string> | null {
  if (bundleCache.has(lang)) return bundleCache.get(lang)!;
  let bundle: Record<string, string> | null = null;
  try {
    const path = join(paiUserDir(), "CONFIG", "locales", `${lang}.json`);
    if (existsSync(path)) {
      const raw = JSON.parse(readFileSync(path, "utf-8"));
      if (raw && typeof raw === "object" && !Array.isArray(raw)) {
        bundle = raw as Record<string, string>;
      }
    }
  } catch {
    bundle = null;
  }
  bundleCache.set(lang, bundle);
  return bundle;
}

function interpolate(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (whole, name) => {
    const v = vars[name];
    return v === undefined ? whole : String(v);
  });
}

/**
 * Resolves `key` for `lang`, falling back to EN for missing locales, missing
 * files, malformed JSON, and missing keys within an otherwise-loaded bundle
 * (key-level fallback — a locale can translate one key and leave the rest).
 * Falls back to the raw key string itself if even EN doesn't have it, so a
 * caller typo never throws mid-hook.
 */
export function t(lang: IssueLang, key: string, vars: Record<string, string | number> = {}): string {
  const bundle = lang && lang !== "en" ? loadLocaleBundle(lang) : null;
  const raw = (bundle && typeof bundle[key] === "string" ? bundle[key] : undefined) ?? EN[key] ?? key;
  return interpolate(raw, vars);
}

