/**
 * work-strings.ts — Locale bundle for auto-filed Work System issue text.
 *
 * Everything the Work System writes into a GitHub issue BODY goes through
 * `t(lang, key, vars)`. Labels (`Type:*`, `Status:*`, `Priority:*`, `Property:*`,
 * `Agent:*`) and the bracketed title prefixes (`[Goal]`, `[Sweep]`,
 * `[Project-Check]`, `[BPE]`, `[Native]`, `[Reminder]`, `[Research]`, `[Queue]`)
 * are classification tokens, not prose — they are never routed through this
 * module and stay in English regardless of locale (dedup keys and the Pulse
 * kanban badge logic depend on them).
 *
 * Design contract:
 *   - Key-level fallback. A locale bundle only needs to cover the keys it has
 *     a translation for; anything missing (or a whole missing locale file)
 *     falls back to the built-in `EN` bundle. Never throws.
 *   - `EN` below is the single source of truth for the key set — every other
 *     locale is a partial override of it. `LIFEOS/TOOLS/InitWorkLocale.ts`
 *     reads `EN`'s keys to generate/validate locale files; nothing else does.
 *   - Interpolation is `{name}` literal substitution only — no expressions,
 *     no plural rules, no nested key references. Translators who need to work
 *     around English pluralization (`{age} days`) phrase around the count
 *     instead (see USER/CONFIG/locales/README.md).
 *   - Locale files live at `<userDir>/CONFIG/locales/<lang>.json` — an
 *     INTERFACE path (LIFEOS/DOCUMENTATION/SystemUserBoundary.md § INTERFACE),
 *     resolved via `paiUserDir()` (LIFEOS/TOOLS/LifeosConfig.ts), never a
 *     literal `LIFEOS/USER/...` string.
 *
 * Consumers:
 *   - LIFEOS/TOOLS/WorkSweep.ts     — 4 sub-sweep issue bodies
 *   - hooks/ReminderRouter.hook.ts  — reminder/research/queue issue bodies
 *   - LIFEOS/TOOLS/InitWorkLocale.ts — locale scaffold/check CLI (reads EN only)
 */

